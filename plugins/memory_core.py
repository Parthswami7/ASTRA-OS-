import os

# ===================================================
# STRICT OFFLINE OVERRIDES (Prevents HuggingFace Network Loops)
# ===================================================
os.environ["TRANSFORMERS_OFFLINE"] = "1"
os.environ["HF_HUB_OFFLINE"] = "1"

import json
import numpy as np
import faiss
from sentence_transformers import SentenceTransformer

class ASTRAMemoryBank:
    def __init__(self, memory_dir="memory_store"):
        """
        Initializes the local FAISS vector database and loads the 
        all-MiniLM-L6-v2 embedding model fully offline.
        """
        print("[ASTRA-MEMORY] Booting Local Vector Database...")
        self.memory_dir = memory_dir
        self.index_path = os.path.join(memory_dir, "ASTRA_memory.index")
        self.text_path = os.path.join(memory_dir, "ASTRA_memory.json")
        
        # Create structural directory if missing
        if not os.path.exists(self.memory_dir):
            os.makedirs(self.memory_dir)
        
        # Load local cached embedding model 
        self.model = SentenceTransformer('all-MiniLM-L6-v2')
        self.dimension = 384  # Vector size generated by all-MiniLM-L6-v2
        
        self.memories = []
        self.index = None
        
        # Initialize or restore database
        self._initialize_database()

    def _initialize_database(self):
        """Looks for an existing index file to load past memories, else creates a fresh flat L2 index."""
        if os.path.exists(self.index_path) and os.path.exists(self.text_path):
            try:
                self.index = faiss.read_index(self.index_path)
                with open(self.text_path, "r", encoding="utf-8") as f:
                    self.memories = json.load(f)
                print("[ASTRA-MEMORY] Past memories successfully loaded.")
            except Exception as e:
                print(f"[WARNING] Memory index corrupted. Initializing fresh bank. Error: {e}")
                self._create_fresh_index()
        else:
            self._create_fresh_index()

    def _create_fresh_index(self):
        """Creates a brand new empty index layout."""
        self.index = faiss.IndexFlatL2(self.dimension)
        self.memories = []
        print("[ASTRA-MEMORY] New Memory Core initialized. No past memories found.")

    def add_memory(self, text, metadata=None):
        """Converts incoming strings into vector embeddings and saves them to the binary matrix index."""
        if not text or not text.strip():
            return
        
        # 1. Generate text embedding vector
        embedding = self.model.encode([text])[0].astype('float32')
        embedding = np.expand_dims(embedding, axis=0)
        
        # 2. Commit vector to FAISS space
        self.index.add(embedding)
        
        # 3. Cache raw string context and structure metadata maps
        memory_entry = {
            "text": text,
            "metadata": metadata or {}
        }
        self.memories.append(memory_entry)
        
        # 4. Instantly serialize to disk to prevent loss on abrupt crash
        self._save_to_disk()

    def search_memory(self, query, top_k=3):
        """Performs a vector spatial search to pull contextual logs matching a user's prompt."""
        if self.index.ntotal == 0:
            return []
        
        # Convert query prompt to lookup vector
        query_embedding = self.model.encode([query])[0].astype('float32')
        query_embedding = np.expand_dims(query_embedding, axis=0)
        
        # Scan space array for closest distance metrics
        distances, indices = self.index.search(query_embedding, min(top_k, self.index.ntotal))
        
        results = []
        for idx, dist in zip(indices[0], distances[0]):
            if idx < len(self.memories) and idx != -1:
                results.append({
                    "context": self.memories[idx]["text"],
                    "metadata": self.memories[idx]["metadata"],
                    "distance": float(dist)
                })
        return results

    def _save_to_disk(self):
        """Serializes FAISS arrays and raw tracking text dictionaries into storage files."""
        faiss.write_index(self.index, self.index_path)
        with open(self.text_path, "w", encoding="utf-8") as f:
            json.dump(self.memories, f, ensure_ascii=False, indent=4)

